FIRST_NAMES: frozenset[str] = frozenset(
    word.replace("ё", "е") for word in _NAMES.split()
)

_WORD_RE = re.compile(r"[^\W\d_]+(?:-[^\W\d_]+)*", re.UNICODE)
_PATRONYMIC_RE = re.compile(r"^[^\W\d_]{2,}(?:вич|ич|вна|чна|ична)$", re.IGNORECASE)


def _key(word: str) -> str:
    return word.casefold().replace("ё", "е")


def capitalize_name(word: str) -> str:
    """«сергей» → «Сергей», «анна-мария» → «Анна-Мария»."""
    return "-".join(part[:1].upper() + part[1:].lower() for part in word.split("-"))


def first_name_from_fio(value: object) -> str | None:
    """Имя из «ФИО» в любом порядке, или None, если угадывать пришлось бы.

    Одно слово — оно и есть имя. Из двух-трёх слов берётся то, что есть в
    словаре имён; иначе — слово перед отчеством. Если признаки спорят или их
    нет, имени нет: обратиться по фамилии и показать её модели хуже, чем не
    обращаться по имени.
    """
    if not isinstance(value, str):
        return None
    words = _WORD_RE.findall(value)
    if not words or len(words) > 3:
        return None
    if len(words) == 1:
        return capitalize_name(words[0])

    keys = [_key(word) for word in words]
    known = [index for index, key in enumerate(keys) if key in FIRST_NAMES]
    if len(known) == 1:
        return capitalize_name(words[known[0]])
    if known:
        return None

    patronymics = [index for index, key in enumerate(keys) if _PATRONYMIC_RE.match(key)]
    if len(patronymics) == 1 and patronymics[0] >= 1:
        return capitalize_name(words[patronymics[0] - 1])
    return None
