"""Роли живого клиента для эвала: собеседника играет модель, а не сценарий.

Вшитые реплики проверяют только тот путь, который мы сами и придумали. Реальный
человек отвечает не теми словами, путается, отвечает не на тот вопрос, молчит по
делу и спрашивает лишнее — и именно на этом ломается человечность, а не на
аккуратной анкете из десяти строк.

Здесь клиента играет отдельная модель с ролью и характером. Она не знает нашей
матрицы и не обязана быть удобной: её задача — вести себя как человек с этой
историей. Оценивают разговор те же метрики, что и раньше (`v4_humanity_score`
поштучно, `dialog_coherence_score` целиком), поэтому числа сравнимы с прежними
прогонами.
"""
from __future__ import annotations

from dataclasses import dataclass, field


CLIENT_SYSTEM_PROMPT = """
Ты играешь роль человека, который пришёл в чат кредитного брокера МБК. Отвечает
живой человек, а не анкета: пиши коротко, как в мессенджере, без списков и без
канцелярита.

ЖЁСТКИЕ ПРАВИЛА:
1. Никогда не выходи из роли и не упоминай, что это тест или что ты модель.
2. Отвечай ТОЛЬКО за клиента. Не пиши реплики специалиста и не продолжай за него.
3. Одна реплика — одно сообщение, обычно 3–15 слов. Иногда одно слово.
4. Держись фактов своей истории. Чего в ней нет — придумай правдоподобно и
   дальше не противоречь себе.
5. Не перечисляй всё сразу. Отвечай на заданный вопрос, а не на все возможные.
6. Если специалист спросил то, что ты уже говорил, — можешь отреагировать как
   человек: «я же сказал», «повторю».
7. Номер телефона называй, когда его спросят, — если он есть в твоей истории.
8. Когда специалист попрощался или сказал, что данные собраны, ответь коротко
   («спасибо», «ага») и больше ничего не добавляй.
""".strip()


@dataclass(frozen=True)
class Persona:
    """Роль клиента: история и манера, а не список реплик."""

    id: str
    description: str
    story: str
    # Черты характера дописываются к роли: именно они ломают гладкий сценарий.
    manner: str
    # Эталон: что бот обязан собрать из живого разговора. Пустой — роль
    # проверяет только человечность (например, отказ давать телефон).
    facts: dict = field(default_factory=dict)
    # Чего в этом разговоре не должно случиться независимо от манеры клиента.
    forbidden_any: list[str] = field(default_factory=list)
    max_turns: int = 22
    # Дойти до конца анкеты может не всякая роль. Тот, кто по сценарию никогда
    # не назовёт телефон, до конца и не дойдёт — это правильное поведение бота,
    # а не провал. Пока признак был общим, роль светилась красным всегда, и
    # прогон переставал что-либо значить.
    expects_completion: bool = True
    # Сколько реплик клиент говорит ПОСЛЕ финала анкеты. Прогон заканчивался
    # вместе с анкетой, и разговор после заявки не проверялся никогда: прод
    # 28.09.2026 — «звонков не будет», «это автоматический текст на странице»
    # в ответ на «менеджер когда позвонит?».
    post_finish_turns: int = 0

    def system_prompt(self) -> str:
        return (
            f"{CLIENT_SYSTEM_PROMPT}\n\n"
            f"ТВОЯ ИСТОРИЯ:\n{self.story}\n\n"
            f"ТВОЯ МАНЕРА:\n{self.manner}"
        )


