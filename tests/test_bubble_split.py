"""Как ответ модели режется на пузыри.

Два пузыря — обычный приём диалога: сначала короткая реакция, потом вопрос.
Ломать его нельзя, он и делает речь живой. А вот вежливая приписка ПОСЛЕ
вопроса («С радостью отвечу.») пользы не несёт и выдаёт бота: два сообщения
прилетают мгновенно одно за другим. Такую приписку приклеиваем к вопросу.
"""
from __future__ import annotations

import pytest

from prompts import split_bubbles


def test_polite_tail_after_a_question_joins_it():
    """Скриншот человека 25.09.2026: вопрос и следом «С радостью отвечу.»."""
    assert split_bubbles(
        "Расскажите, что вас интересует?\n\nС радостью отвечу."
    ) == ["Расскажите, что вас интересует? С радостью отвечу."]


def test_reaction_before_the_question_stays_a_separate_bubble():
    """Обычный ход анкеты: сопережили, потом спросили."""
    assert split_bubbles(
        "Поняла, ситуация знакомая.\n\nЕсть ли у вас недвижимость в собственности?"
    ) == [
        "Поняла, ситуация знакомая.",
        "Есть ли у вас недвижимость в собственности?",
    ]


@pytest.mark.parametrize(
    "text, why",
    [
        (
            "Какая сумма вам нужна?\n\nЭто нужно, чтобы подобрать вариант, "
            "который подойдёт именно вам, и не задавать лишних вопросов дальше.",
            "длинное пояснение несёт смысл, его не клеим",
        ),
        (
            "Сколько вам полных лет?\n\nА есть ли действующие кредиты?",
            "второй вопрос — отдельная мысль",
        ),
    ],
)
def test_meaningful_second_bubble_survives(text, why):
    assert len(split_bubbles(text)) == 2, why


def test_only_the_last_tail_joins():
    assert split_bubbles(
        "Поняла вас.\n\nКакая сумма нужна?\n\nСпасибо."
    ) == ["Поняла вас.", "Какая сумма нужна? Спасибо."]


def test_single_bubble_is_untouched():
    assert split_bubbles("Добрый день! Чем могу помочь?") == [
        "Добрый день! Чем могу помочь?"
    ]


def test_tail_after_a_request_joins_it_too():
    """Стенд 25.09.2026: просьба точкой, следом «Я на связи и готова разобраться.»."""
    text = (
        "Напишите, пожалуйста, что именно вас интересует."
        + chr(10) * 2
        + "Я на связи и готова разобраться."
    )
    assert split_bubbles(text) == [
        "Напишите, пожалуйста, что именно вас интересует. "
        "Я на связи и готова разобраться."
    ]
