"""Whole negative visibility acts retain the model's wording and local polarity."""
from __future__ import annotations

import pytest

import core
import entry_routing
from state import init_state
from utils import guard_bubbles


TAIL = "Если есть новый вопрос по деньгам или долгам — рада помочь прямо в этом чате."


@pytest.mark.parametrize("limitation", [
    "К сожалению, отсюда я не вижу статус вашей заявки и не могу её проверить.",
    "К сожалению, отсюда я не вижу статус вашей заявки и не могу проверить, почему ещё не связались.",
    "К сожалению, статус вашей заявки я не вижу.",
    "Здесь я не вижу статус вашей заявки.",
    "Сейчас в чате я не вижу статус вашей заявки и не могу проверить её.",
    "Статус вашей заявки мне недоступен и я не могу проверить вашу заявку.",
    "Я не вижу статус вашей заявки и не могу его проверить.",
    "Я не вижу статус вашей заявки и не могу проверить статус.",
    "Я не вижу статус вашей заявки и не могу проверить, почему вам ещё не позвонили.",
    "Я не вижу статус вашей заявки и не могу проверить, почему с вами пока не связались.",
    "Я не вижу статус вашей заявки и не могу проверить, почему до сих пор не перезвонили.",
])
def test_courtesy_position_and_a_denied_check_remain_one_honest_act(limitation):
    assert guard_bubbles([limitation, TAIL], scenario=entry_routing.EXISTING) == [limitation, TAIL]


@pytest.mark.parametrize("limitation", [
    "К сожалению, отсюда я не вижу статус вашей заявки и не могу её проверить.",
    "К сожалению, отсюда я не вижу статус вашей заявки и не могу проверить, почему ещё не связались.",
])
def test_the_actual_existing_answer_reaches_commit_without_wording_replacement(limitation):
    state = init_state()
    state["entry"] = {"scenario": entry_routing.EXISTING, "intent": "existing", "source": "dictionary"}
    result = core.commit_turn(state, "Что с моей заявкой?", limitation + "\n\n" + TAIL)
    assert result["messages"] == [limitation, TAIL]
    assert not (result["current_state"].get("script") or {}).get("asked")


