# Вежливый хвостик после вопроса: короткая фраза без своего вопроса, которая
# ничего не добавляет («С радостью отвечу.», «Спасибо.»). Отдельным пузырём он
# прилетает мгновенно следом за вопросом и выдаёт бота — человек так не пишет.
# Замечено на стенде 25.09.2026.
_POLITE_TAIL_CHARS = 45
# Просьба рассказать — такой же вопрос по смыслу, только с точкой на конце.
_ASK_OPENERS = ("Напишите", "Расскажите", "Подскажите", "Уточните",
                "Опишите", "Оставьте")


def asks_something(bubble: str) -> bool:
    """Задаёт ли реплика вопрос: знак вопроса или просьба «Подскажите…»."""
    text = (bubble or "").strip()
    return "?" in text or text.startswith(_ASK_OPENERS)


def _join_polite_tail(bubbles: list[str]) -> list[str]:
    """Приклеивает к вопросу короткую вежливую приписку, если она идёт следом.

    Реакция ПЕРЕД вопросом — приём живой речи, её не трогаем: первый пузырь
    отвечает на сказанное, второй спрашивает дальше.
    """
    if len(bubbles) < 2:
        return bubbles
    tail = bubbles[-1]
    if "?" in tail or len(tail) > _POLITE_TAIL_CHARS:
        return bubbles
    asked = bubbles[-2].rstrip()
    if not asked.endswith("?") and not asked.startswith(_ASK_OPENERS):
        return bubbles
    return [*bubbles[:-2], f"{bubbles[-2]} {tail}"]


def split_bubbles(text: str, max_bubbles: int = 3) -> list[str]:
    """Разрезает свободный текст ответа на «пузыри» по пустым строкам."""
    if not text:
        return []
    chunks = [chunk.strip() for chunk in text.replace("\r\n", "\n").split("\n\n")]
    bubbles = [chunk for chunk in chunks if chunk]
    if not bubbles:
        flat = text.strip()
        return [flat] if flat else []
    return _join_polite_tail(bubbles[:max_bubbles])


