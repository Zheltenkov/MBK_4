# Имя и пол ассистента — настройка, а не константа: заказчик меняет их сам,
# не пересобирая образ. Пол влияет не на одно слово, а на всю речь о себе:
# по-русски «понял» и «поняла» — разные формы, и женское имя при мужских
# глаголах читается как сбой. Поэтому род прокидывается в промпт явным
# правилом, а не оставляется на догадку модели по имени.
_DEFAULT_ASSISTANT_NAME = "Ника"
_FEMALE = "female"
_MALE = "male"


def _configured_name() -> str:
    return (os.getenv("MBK_ASSISTANT_NAME") or "").strip() or _DEFAULT_ASSISTANT_NAME


def _configured_gender() -> str:
    raw = (os.getenv("MBK_ASSISTANT_GENDER") or "").strip().lower()
    return _MALE if raw == _MALE else _FEMALE


ASSISTANT_NAME = _configured_name()
ASSISTANT_GENDER = _configured_gender()
_IS_FEMALE = ASSISTANT_GENDER == _FEMALE


def _g(masculine: str, feminine: str) -> str:
    """Форма слова по полу ассистента."""
    return feminine if _IS_FEMALE else masculine


