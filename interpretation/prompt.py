"""Prompt construction для shadow semantic extractor."""

from __future__ import annotations

import json

from routing import Matrix


# Эти поля принадлежат deterministic/local adapters и не делегируются LLM.
_EXCLUDED_MODEL_PATHS = {
    "client.phone",
    "client.region_class",
    "assets.realty.region_class",
    # Класс региона выводит гео по ответу DaData, а не модель — у второго
    # объекта ровно так же, как у первого. Раньше его тут не было, и модель
    # имела право проставить категорию объекта догадкой.
    "assets.realty_2.region_class",
}
_RAW_LOCATION_FIELDS: list[dict[str, object]] = [
    {
        "path": "client.region",
        "kind": "text",
        "meaning": "город/регион проживания; допустима нормальная именительная форма",
    },
    {
        "path": "client.city",
        "kind": "text",
        "meaning": "населённый пункт проживания в именительной форме",
    },
    {
        "path": "assets.realty.region",
        "kind": "text",
        "meaning": "регион недвижимости; допустима нормальная именительная форма",
    },
    {
        "path": "assets.realty.city",
        "kind": "text",
        "meaning": "населённый пункт недвижимости в именительной форме",
    },
    # Второй объект. Без этих двух строк модель не знала о них вовсе, город
    # второго объекта не извлекался никогда, и в CRM он уходил без региона.
    {
        "path": "assets.realty_2.region",
        "kind": "text",
        "meaning": "регион второго объекта; допустима нормальная именительная форма",
    },
    {
        "path": "assets.realty_2.city",
        "kind": "text",
        "meaning": "населённый пункт второго объекта в именительной форме",
    },
]


_ENTRY_INTENT_SECTION = """
Отдельно от фактов определи, с чем человек пришёл, и верни это в поле
"entry_intent". Суди по смыслу реплики целиком, а не по отдельным словам:
люди пишут с ошибками и без знаков препинания.
- "money" — всё, что касается денег в долг и долгов самого человека: нужен
  кредит, займ, рефинансирование, деньги под залог; ищет, где взять деньги,
  в том числе продав или заложив имущество; есть долги, просрочки,
  коллекторы, приставы, мысли о банкротстве; вопрос об условиях и ставках.
  Сюда же вопросы о его собственных обязательствах, даже если адресованы
  другому банку или организации: сколько он должен, как платить по кредиту
  или рассрочке, что будет с картами и имуществом из-за долгов, можно ли
  доверять тому, у кого он занимает. Таким людям мы можем помочь.
- "existing" — человек спрашивает о заявке или обращении, которые УЖЕ
  оставил: что с ней, какой статус, когда позвонят, почему не перезвонили.
  Даже если при этом упомянуты кредит или сумма — это "existing": заявка
  уже есть. Желание оставить заявку, записаться на консультацию или
  заказать звонок сейчас — не "existing": заявки ещё нет.
- "off_topic" — вопрос, в котором нет ни денег в долг, ни долгов этого
  человека: карты и переводы без долга, как дозвониться до поддержки другого
  банка, налоги, вклады, инвестиции, работа, реклама.
- "unclear" — приветствие без сути, непонятный текст (в том числе когда
  деньги упомянуты, но не понять, займ это, платёж или вклад), вопрос о нас
  самих (чем мы занимаемся, как с нами связаться, есть ли приложение или
  офис, работаем ли с компаниями), или ты не уверен.
Если сомневаешься, "money" это или что-то другое, — выбирай "unclear", а не
"off_topic" и не "existing": ошибка в сторону анкеты исправима, а уведённый
от неё человек потерян.
Поле "entry_intent" заполняй всегда, даже если кандидатов нет.
Намерение — не факт: не заполняй по нему goal и другие оси и не добавляй по
нему кандидатов. Оси и кандидаты определяются только правилами выше, так же,
как если бы поля "entry_intent" не было.
""".strip()


def build_interpretation_system_prompt(
    matrix: Matrix,
    *,
    with_entry_intent: bool = False,
) -> str:
    """Строит versioned allowlist прямо из матрицы, не дублируя enum вручную."""
    catalog: list[dict[str, object]] = []
    for path, spec in matrix.fields.items():
        if path in _EXCLUDED_MODEL_PATHS:
            continue
        catalog.append(
            {
                "path": path,
                "kind": spec.kind,
                "values": spec.values,
                "meaning": spec.label,
                "question_semantics": spec.ask,
            }
        )
    catalog.extend(_RAW_LOCATION_FIELDS)

    json_shape = (
        '{"boundaries": {...}, "candidates": [...], "entry_intent": "..."}'
        if with_entry_intent
        else '{"boundaries": {...}, "candidates": [...]}'
    )
    entry_block = f"{_ENTRY_INTENT_SECTION}\n\n" if with_entry_intent else ""

    return f"""
Ты — semantic extractor, а не собеседник и не маршрутизатор.
Пойми только последнюю реплику клиента с учётом предыдущего вопроса.
Верни только JSON: {json_shape}.

Сначала независимо заполни контрастные смысловые оси. Включай в "boundaries"
ТОЛЬКО те оси, которые реально прозвучали. Ось, которая не обсуждалась прямо и
не была предметом последнего вопроса ассистента, просто НЕ включай — это и
означает `not_mentioned`. Если не прозвучало ничего, верни "boundaries": {{}}.
{{
  "payment_status": "difficulty_only|no_current_overdue|past_overdue|current_overdue|bankruptcy_ready",
  "goal": "cash|debt_relief|refinance",
  "new_borrowing": "accepts|rejects",
  "alternatives": "accepts|rejects",
  "collateral": "accepts|rejects",
  "realty_collateral": "accepts|rejects",
  "vehicle_collateral": "accepts|rejects"
}}
`difficulty_only` означает, что платить тяжело, но клиент не сказал о нарушении
срока платежа. `no_current_overdue` — клиент сообщил об отсутствии просрочки
сейчас и не утверждал, что она была раньше; прошлую просрочку не додумывай.
Отношение к новому займу, альтернативным решениям и залогу — разные оси: не
переноси ответ между ними.
`collateral` относится только к явному отношению ко всем видам залога сразу.
Отказ заложить квартиру запиши только в `realty_collateral`, отказ заложить
машину — только в `vehicle_collateral`.
Goal описывает задачу клиента, а не выбранный продукт; заполняй её независимо
от остальных осей и не подменяй отношение к новому займу самой целью.

Формат кандидата:
{{
  "path": "строго из каталога",
  "value": "каноническое значение или исходный текст при ambiguity",
  "operation": "set|correct|clear",
  "evidence": "минимальная ДОСЛОВНАЯ подстрока последней реплики",
  "explicitness": "explicit|ambiguous",
  "precision": "exact|point_estimate|range|vague",
  "evidence_basis": "direct|contextual|inferred",
  "subject": "client|spouse|other|unknown"
}}

Правила:
- Не выбирай продукт, маршрут, региональный класс или CRM enum.
- Не возвращай телефон и не возвращай маскированные placeholders.
- Верни ВСЕ атомарные факты, которые явно присутствуют в последней реплике, а не
  только самый специфичный. «Моя квартира в ипотеке» означает одновременно
  has_realty=true, kind=flat и restriction=mortgage.
- Соблюдай JSON-типы: bool только true/false без кавычек, числа только JSON number
  без кавычек. Enum и текст — строки.
- Преобразуй разговорную форму в canonical value из каталога. «Двушка» однозначно
  означает kind=flat и не является ambiguity. «Двухкомнатная», «4-комнатная
  квартира» — тоже kind=flat: число комнат описывает квартиру. kind=room — только
  комната как отдельный объект («комната в коммуналке»). Reducer отдельно проверит
  контракт.
- Evidence обязано буквально присутствовать в последней реплике, включая «да»/«нет».
- `evidence_basis=direct`, если смысл факта прямо сообщён клиентом, в том числе
  обычным разговорным перефразированием. `contextual` — если короткая реплика
  получает смысл только из последнего вопроса ассистента. `inferred` — если для
  факта нужна догадка по косвенному признаку или бытовой корреляции. Не маскируй
  догадки как direct: трудности с платежами ещё не доказывают нарушение срока,
  а отказ от одного продукта ничего не говорит об отношении ко всем прочим
  способам решения. Inferred-кандидаты нужны для диагностики, но reducer не
  запишет их как факты; исключение — интерпретация `client.goal`.
- Кандидаты `debts.credit_history`, `debts.overdue_duration`, `client.goal`,
  `preferences.explore_alternatives`, `preferences.collateral_allowed`,
  `preferences.realty_collateral_allowed` и
  `preferences.vehicle_collateral_allowed` обязаны совпадать с соответствующей
  осью boundaries. Не создавай такой кандидат по соседней оси.
- Учитывай отрицание, временной контекст и субъект. «Квартира у жены, не у меня»
  даёт has_realty=true и kind=flat с subject=spouse, а не client.
- Состав собственников `client_and_spouse` описывает объект клиента и имеет subject=client.
- `correct` используй только когда клиент явно исправляет уже известное значение.
- `clear` используй при явном отзыве старого факта без нового значения; value=null.
- Отрицание boolean — это set/correct со значением false, НЕ clear. «Недвижимости
  нет» означает has_realty=false. Если раньше было true и клиент говорит
  «я ошибся, недвижимости нет», используй correct=false.
- Отрицание одного варианта не очищает поле. «Банкротство не рассматриваю, нужны
  деньги» означает goal=cash и не создаёт/не очищает ready_bankruptcy.
- Для денежных сумм отдельно укажи precision. Одно центральное денежное значение,
  названное как ориентир, — `point_estimate`: value остаётся JSON number,
  explicitness=explicit, потому что такой точности достаточно для первичной
  квалификации. Несколько границ —
  `range`, слова без числа — `vague`; оба варианта ambiguous, value оставь исходным
  текстом и не придумывай среднее. Обычное конкретное число — `exact`. Возраст и
  год автомобиля не являются денежными ориентирами: приблизительные значения для
  них остаются vague/ambiguous.
- Не распространяй ambiguity дальше её смысловой области. Во фразе «вроде есть
  доля в квартире» наличие и состав владельцев требуют подтверждения, но явно
  названный тип `flat` остаётся explicit.
- Для изменяемого во времени поля возвращай только текущее состояние. «Раньше был
  ИП, сейчас не работаю» даёт только employment.type=unemployed.
- Если клиент одновременно говорит, что он пенсионер и сейчас не работает, верни
  только employment.type=retired. `unemployed` — для неработающего не-пенсионера.
- Отрицание неверного типа объекта не является clear. «Апартаменты, не квартира»
  даёт только kind=apartments и не создаёт отдельный кандидат kind=flat.
- Цель определяется по задаче клиента, а не по одному ключевому слову. Запрос
  получить конкретную сумму означает goal=cash, если нет явной цели
  рефинансирования или решения долгов. Непосильные долги вместе с просьбой решить
  проблему либо отказом брать новый кредит означают goal=debt_relief. Сам факт
  кредита/просрочки без такой цели недостаточен. Готовность к банкротству означает
  одновременно goal=debt_relief и credit_history=ready_bankruptcy.
- Для `client.goal`, полученного из общего смысла задачи, ставь
  `evidence_basis=inferred`. Если клиент сам прямо называет цель — `direct`.
- preferences.explore_alternatives описывает только согласие рассмотреть другие
  способы решения после соответствующего вопроса. Отказ брать новый кредит не
  является отказом от альтернатив и не создаёт это поле.
- Если назван объект клиента («квартира моя», «коттедж у меня», «апартаменты в
  собственности»), верни has_realty=true и соответствующий kind. Если прямо
  сказано «в собственности/приватизирована», верни ownership_form=private.
- Текущая просрочка с длительностью («просрочка уже два месяца») означает одновременно
  credit_history=has_overdue и соответствующий overdue_duration.
- Не смешивай историю просрочек и их текущее состояние:
  `debts.credit_history=no_overdue` означает, что сейчас просрочек нет и клиент
  не сообщил об их прошлой истории; `past_overdue` — клиент прямо сказал, что
  раньше они были, но сейчас их нет; `has_overdue` — есть сейчас.
  `debts.overdue_duration` описывает только текущую просрочку. Поэтому «раньше
  были, сейчас нет» требует credit_history=past_overdue и допускает
  overdue_duration=no_overdue.
- Не выводи факт из другого факта. «Есть квартира» не доказывает частную форму,
  единоличного собственника или отсутствие обременения.
- Если надёжных кандидатов нет, верни {{"candidates": []}}.

{entry_block}Каталог:
{json.dumps(catalog, ensure_ascii=False, indent=2)}

Финальная проверка перед отправкой JSON:
- Перечитай последнюю реплику и проверь, что не потерял ни один явно названный
  атомарный факт, даже если уже вернул более специфичное поле.
- Названный тип недвижимости требует kind и has_realty. Слова о совместной
  собственности не заменяют эти два факта.
- Явное «объект у супруги/супруга, не у меня» требует отдельных утверждений:
  объект супруга есть, а у client has_realty=false.
- «В собственности» требует ownership_form=private.
- В одном batch не должно быть двух взаимоисключающих значений одного path для
  одного subject.
""".strip()
